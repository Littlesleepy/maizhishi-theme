import { afterEach, describe, expect, it, vi } from 'vitest'
import { createOrchisEvolution, createOrchisEvolutionAudio } from './native-evolution'

afterEach(() => { document.body.replaceChildren(); vi.unstubAllGlobals() })
describe('native evolution lifecycle', () => {
  it('releases a loading transition without committing and removes its body layer', async () => {
    vi.stubGlobal('matchMedia', () => ({ matches:false }))
    vi.stubGlobal('fetch', () => new Promise(() => {}))
    vi.spyOn(HTMLCanvasElement.prototype, 'getContext').mockReturnValue({clearRect:vi.fn()} as unknown as CanvasRenderingContext2D)
    const display=document.createElement('div'), button=document.createElement('button')
    document.body.append(display,button)
    vi.spyOn(display,'getClientRects').mockReturnValue([new DOMRect(0,0,300,400)] as unknown as DOMRectList)
    const commit=vi.fn(), remove=vi.spyOn(document,'removeEventListener')
    const controller=createOrchisEvolution(display,button)
    const pending=controller.play(commit)
    controller.dispose()
    expect(await pending).toBe(false)
    expect(commit).not.toHaveBeenCalled()
    expect(button.disabled).toBe(false)
    expect(document.querySelector('.evolution-layer')).toBeNull()
    expect(remove).toHaveBeenCalledWith('visibilitychange',expect.any(Function))
    expect(await controller.play(commit)).toBe(false)
  })
  it('keeps gesture audio at 10% and removes all listeners on disposal', async () => {
    const media=document.createElement('audio')
    vi.spyOn(media,'pause').mockImplementation(()=>{})
    vi.spyOn(media,'play').mockResolvedValue()
    const errorOff=vi.spyOn(media,'removeEventListener')
    const docOff=vi.spyOn(document,'removeEventListener'), pageOff=vi.spyOn(window,'removeEventListener')
    const audio=createOrchisEvolutionAudio(media)
    expect(media.volume).toBe(.1)
    expect(await audio.play()).toBe(true)
    audio.dispose()
    expect(errorOff).toHaveBeenCalledWith('error',expect.any(Function))
    expect(docOff).toHaveBeenCalledWith('visibilitychange',expect.any(Function))
    expect(pageOff).toHaveBeenCalledWith('pagehide',expect.any(Function))
    expect(await audio.play()).toBe(false)
  })
})
